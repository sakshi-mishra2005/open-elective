import json
from pathlib import Path
import pandas as pd
import streamlit as st
from evaluate import run_evaluation, load_tasks, score_response, generate_demo_response

ROOT = Path(__file__).parent
TEMPLATE_PATH = ROOT / "templates" / "templates.json"
EXAMPLES_PATH = ROOT / "templates" / "few_shot_examples.json"
TASKS_PATH = ROOT / "data" / "tasks.json"
OUTPUT_DIR = ROOT / "outputs"
OUTPUT_DIR.mkdir(exist_ok=True)

st.set_page_config(page_title="Prompt Lab", page_icon="🧪", layout="wide")
st.title("🧪 Prompt Lab")
st.caption("Prompt engineering playground: templates, few-shot examples, A/B testing, and a 15-task evaluation harness.")

with open(TEMPLATE_PATH, encoding="utf-8") as f:
    templates = json.load(f)
with open(EXAMPLES_PATH, encoding="utf-8") as f:
    example_packs = json.load(f)

st.sidebar.header("Workspace")
mode = st.sidebar.radio("Choose a section", ["Prompt Playground", "A/B Evaluation", "Templates & Examples", "About"])

if mode == "Prompt Playground":
    st.subheader("Test a prompt")
    template_names = list(templates.keys())
    chosen = st.selectbox("Template", template_names)
    template = templates[chosen]
    st.write("**Purpose:**", template["purpose"])
    prompt = st.text_area("Prompt template", template["template"], height=150)
    task_input = st.text_area("Input text / task", "Solar panels convert sunlight into electricity. They can reduce electricity bills and carbon emissions, but output depends on sunlight and installation cost.", height=120)
    use_examples = st.checkbox("Include few-shot examples when available", value=False)
    if st.button("Generate demo response", type="primary"):
        rendered_prompt = prompt.replace("{input}", task_input)
        if use_examples and chosen in example_packs:
            st.info("Few-shot examples selected. This offline demo uses a deterministic local simulator, not a remote LLM.")
        response = generate_demo_response(chosen, task_input, prompt, example_packs.get(chosen, []) if use_examples else [])
        st.markdown("#### Output")
        st.code(response, language="json" if chosen == "Structured JSON" else "text")
        st.caption("Offline demo mode: output is generated by simple local logic. Connect an LLM API to evaluate real model behaviour.")
        st.download_button("Download prompt + output", json.dumps({"template": chosen, "prompt": rendered_prompt, "output": response}, indent=2), file_name="prompt_test.json")

elif mode == "A/B Evaluation":
    st.subheader("A/B evaluation on 15 tasks")
    st.write("Compare a baseline prompt with an improved prompt using the same 15 benchmark tasks. The included scorer checks task-specific rules and is intentionally transparent.")
    task_df = pd.DataFrame(load_tasks(TASKS_PATH))
    st.dataframe(task_df[["id", "scenario", "input", "expected"]], use_container_width=True, hide_index=True)
    c1, c2 = st.columns(2)
    with c1:
        prompt_a = st.text_area("Prompt A — baseline", "Answer the task briefly: {input}", height=120)
    with c2:
        prompt_b = st.text_area("Prompt B — improved", "Follow the task requirements exactly. Be concise and preserve key facts: {input}", height=120)
    if st.button("Run evaluation on all 15 tasks", type="primary"):
        results, summary = run_evaluation(TASKS_PATH, prompt_a, prompt_b)
        results_path = OUTPUT_DIR / "ab_results.csv"
        results.to_csv(results_path, index=False)
        st.success("Evaluation complete.")
        m1, m2, m3 = st.columns(3)
        m1.metric("Prompt A average score", f"{summary['A']:.1f}%")
        m2.metric("Prompt B average score", f"{summary['B']:.1f}%")
        m3.metric("Difference (B − A)", f"{summary['B'] - summary['A']:+.1f} pp")
        st.dataframe(results, use_container_width=True, hide_index=True)
        st.bar_chart(pd.DataFrame({"Prompt A": results["score_a"], "Prompt B": results["score_b"]}, index=results["id"]))
        st.download_button("Download results CSV", results.to_csv(index=False), file_name="ab_results.csv", mime="text/csv")
        st.warning("These scores measure the included local simulator and rubric, not a general-purpose LLM. For a valid model study, connect the same model/API to both prompts and retain these 15 task inputs.")

elif mode == "Templates & Examples":
    st.subheader("Prompt template library")
    for name, item in templates.items():
        with st.expander(name):
            st.write(item["purpose"])
            st.code(item["template"])
            st.write("**Few-shot pack**")
            st.json(example_packs.get(name, []))
    st.caption(f"{len(templates)} templates included.")

else:
    st.subheader("Project overview")
    st.markdown("""
**Included features**
- 6 reusable prompt templates
- Few-shot example packs
- Three live demo scenarios: summarization, classification, structured JSON
- A/B evaluation harness with 15 tasks
- CSV export and result chart
- Offline mode; no API key required to run

**Run**
1. Install Python 3.10 or newer.
2. In this folder, run `pip install -r requirements.txt`
3. Run `streamlit run app.py`

**Limitations**
The default response generator and scorer are deterministic educational demos. They do not call an LLM. For model-quality claims, integrate an LLM API and re-run the benchmark.
""")
